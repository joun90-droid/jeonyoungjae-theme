def build_stock(theme_id, idx, row):
    code, name, market, tag, risk, growth, score, role, focus = row
    theme = next(t for t in THEMES if t["id"] == theme_id)
    is_us = market in ("NASDAQ", "NYSE", "US")
    display_code = code.split(".")[0] if is_us else code
    currency = "USD" if is_us else "KRW"
    thesis = f"{name}은(는) {theme['name']} 테마에서 {role} 포지션이며, 핵심 재료는 {focus}입니다."
    sector_view = (
        f"{theme['sectorPath']} "
        f"현재 컨센서스성 전망은 '{theme['outlook']}'이며, {name}은(는) 그중 '{role}' 역할로 섹터 방향성을 추종·증폭합니다."
    )
    logic = (
        f"① 상위 테마 수요({theme['catalysts'][0]})가 존재하고, "
        f"② 그 수요가 {name}의 {focus}로 연결되며, "
        f"③ 위험도 {risk}점·성장 {growth}점을 감안해 포지션 크기를 조절하는 것이 논리의 뼈대입니다. "
        f"단순 테마명 연관이 아니라 '{focus} → 실적/가이던스 변화'가 확인될 때 설득력이 완성됩니다."
    )
    safe_id = code.replace(".", "_")
    return {
        "id": f"{theme_id}_{idx:02d}_{safe_id}",
        "theme": theme_id,
        "name": name,
        "code": code,
        "displayCode": display_code,
        "symbol": code,
        "market": market,
        "currency": currency,
        "tag": tag,
        "risk": risk,
        "growth": growth,
        "score": score,
        "role": role,
        "focus": focus,
        "thesis": thesis,
        "sectorView": sector_view,
        "logic": logic,
        "materials": mats(theme_id, focus, name),
        "pros": [f"{theme['name']} 직접 연관", f"핵심 관찰지표: {focus}", f"포지션 성격: {role}"],
        "cons": [theme["risks"][0], "테마 수급 변동성", "재료 공백 시 급락 가능"],
        "riskLabel": "낮음" if risk < 50 else ("보통" if risk < 70 else "높음"),
        "growthLabel": "낮음" if growth < 65 else ("보통" if growth < 80 else "높음"),
        "chartProfile": {
            "demand": min(95, growth + 5),
            "supply": max(25, 100 - risk + 10),
            "policy": 60 + (theme["heat"] // 5),
            "earnings": max(30, score - 15),
            "liquidity": 70 if is_us or market == "KOSPI" else 40,
            "volatility": risk,
        },
    }


def main():
    stocks = []
    for tid, rows in RAW.items():
        assert len(rows) >= 10, tid
        for i, row in enumerate(rows, 1):
            stocks.append(build_stock(tid, i, row))

    payload = {
        "themes": THEMES,
        "stocks": stocks,
        "updatedAt": "2026-07-31",
        "meta": {
            "themeCount": len(THEMES),
            "stockCount": len(stocks),
            "minPerTheme": min(sum(1 for s in stocks if s["theme"] == t["id"]) for t in THEMES),
        },
    }
    (ROOT / "data.js").write_text(
        "window.THEME_DATA = " + json.dumps(payload, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8",
    )
    instruments = [
        {
            "code": s["code"],
            "symbol": s.get("symbol") or s["code"],
            "market": s["market"],
            "currency": s.get("currency") or "KRW",
        }
        for s in stocks
    ]
    # unique by code
    uniq = {i["code"]: i for i in instruments}
    (ROOT / "codes.json").write_text(
        json.dumps(list(uniq.values()), ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print("themes", len(THEMES), "stocks", len(stocks), "min/theme", payload["meta"]["minPerTheme"], "instruments", len(uniq))


if __name__ == "__main__":
    main()
